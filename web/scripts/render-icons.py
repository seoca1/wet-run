#!/usr/bin/env python3
"""Render the wet_run PWA icon set with a Gibson terminal aesthetic.

Replaces the placeholder "WR" wordmark generated by the original
`scripts/generate-icons.py`. The new artwork keeps the existing PWA palette
(black + neon-green #00ff41 from `manifest.json` -> `theme_color`) and adds
the visual identity the game actually uses: a circular border, scan-line
fill, and a jack-plug glyph (the console cowboy's literal icon).

Sizes written: every `sizes` entry in `public/manifest.json`. Currently
192x192 and 512x512 (the only entries the manifest declares). The script
discovers sizes dynamically so future manifest entries are picked up
without code edits.

Pipeline:
  1. Render at 512x512 (vector-sharp: straight lines, integer coords).
  2. Downscale to each requested size with `Image.LANCZOS` so the borders
     and glyph edges stay crisp at 192.

No external network — uses PIL only.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Iterable

from PIL import Image, ImageDraw

SCRIPT_DIR = Path(__file__).resolve().parent
WEB_DIR = SCRIPT_DIR.parent
PUBLIC_DIR = WEB_DIR / "public"
MANIFEST = PUBLIC_DIR / "manifest.json"
ICONS_DIR = PUBLIC_DIR / "icons"

# Gibson-flavored palette (matches manifest.json theme_color).
BG = (0, 0, 0)
NEON = (0, 255, 65)
NEON_DIM = (0, 200, 52)

# Render supersample: always draw at this resolution then downscale.
RENDER_SIZE = 512


def _read_manifest_sizes() -> list[int]:
    """Return all icon sizes (square px) declared in `manifest.json`."""
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    sizes: list[int] = []
    for icon in data.get("icons", []):
        spec = icon.get("sizes", "")
        for token in spec.split():
            token = token.strip()
            if "x" not in token:
                continue
            w, _, h = token.partition("x")
            if w == h and w.isdigit():
                sizes.append(int(w))
    if not sizes:
        # Fall back to the well-known sizes if manifest is unparseable.
        sizes = [192, 512]
    return sorted(set(sizes))


def _draw_icon(size: int) -> Image.Image:
    """Compose the icon at `size`. All coordinates are in final-pixel units."""
    img = Image.new("RGB", (size, size), BG)
    draw = ImageDraw.Draw(img)

    # Geometry constants scale with `size`.
    pad = max(2, size // 32)
    border_w = max(2, size // 64)

    # 1. Outer rectangular border (CRT monitor frame).
    draw.rectangle(
        [pad, pad, size - pad - 1, size - pad - 1],
        outline=NEON,
        width=border_w,
    )

    # 2. Scan-line fill: very faint horizontal lines inside the frame.
    scanline_color = (0, 30, 8)
    for y in range(pad + border_w + 2, size - pad - border_w - 1, max(2, size // 96)):
        draw.line([(pad + border_w + 1, y), (size - pad - border_w - 2, y)], fill=scanline_color)

    # 3. Inner circular border (jack port ring).
    cx = cy = size // 2
    ring_outer_r = size * 5 // 16
    ring_inner_r = ring_outer_r - max(2, size // 32)
    draw.ellipse(
        [cx - ring_outer_r, cy - ring_outer_r, cx + ring_outer_r, cy + ring_outer_r],
        outline=NEON,
        width=max(2, size // 64),
    )

    # 4. Jack plug glyph: vertical bar with a small horizontal bar near the top
    #    and three small "pin" marks inside the ring.
    plug_w = max(2, size // 32)
    plug_h = ring_outer_r + max(4, size // 16)
    plug_top = cy - plug_h // 2
    plug_bottom = plug_top + plug_h
    # Main shaft
    draw.rectangle(
        [cx - plug_w, plug_top, cx + plug_w, plug_bottom],
        fill=NEON,
    )
    # Tip — wider cap at the top of the shaft
    tip_w = plug_w * 3
    draw.rectangle(
        [cx - tip_w, plug_top - max(2, size // 64), cx + tip_w, plug_top + max(2, size // 64)],
        fill=NEON,
    )
    # Three pin marks inside the ring (suggesting ICE lattice).
    pin_r = max(1, size // 128)
    for offset_y in (-ring_outer_r // 2, 0, ring_outer_r // 2):
        draw.ellipse(
            [cx - pin_r, cy + offset_y - pin_r, cx + pin_r, cy + offset_y + pin_r],
            fill=NEON_DIM,
        )

    # 5. Corner glyphs: small triangle notches on each corner of the border
    #    (Gibson terminal / HUD framing).
    notch = max(3, size // 24)
    for (cx0, cy0, dx, dy) in [
        (pad, pad, 1, 1),
        (size - pad - 1, pad, -1, 1),
        (pad, size - pad - 1, 1, -1),
        (size - pad - 1, size - pad - 1, -1, -1),
    ]:
        draw.polygon(
            [
                (cx0, cy0),
                (cx0 + dx * notch, cy0),
                (cx0, cy0 + dy * notch),
            ],
            fill=NEON,
        )

    # 6. "WR" wordmark near the bottom — small, monospace-styled.
    #    Use PIL's default bitmap font for portability (no font files required).
    try:
        from PIL import ImageFont
        font_size = max(8, size // 12)
        try:
            font = ImageFont.truetype("/System/Library/Fonts/Menlo.ttc", font_size)
        except OSError:
            try:
                font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", font_size)
            except OSError:
                font = ImageFont.load_default()
        text = "WR"
        bbox = draw.textbbox((0, 0), text, font=font)
        tw = bbox[2] - bbox[0]
        th = bbox[3] - bbox[1]
        tx = (size - tw) // 2
        ty = size - pad - border_w - th - max(2, size // 64)
        draw.text((tx, ty), text, fill=NEON, font=font)
    except Exception:
        # If the text rendering fails for any reason, the icon is still
        # valid without the wordmark — the jack-plug is the primary mark.
        pass

    return img


def render_all(sizes: Iterable[int]) -> list[dict]:
    """Render every requested size and write to public/icons/."""
    sizes_list = sorted(set(sizes))
    # Always render at the supersampled size first, then downscale.
    master = _draw_icon(RENDER_SIZE)
    results: list[dict] = []
    for size in sizes_list:
        if size == RENDER_SIZE:
            img = master
        else:
            img = master.resize((size, size), Image.LANCZOS)
        out_path = ICONS_DIR / f"icon-{size}.png"
        img.save(out_path, "PNG", optimize=True)
        results.append({
            "size": size,
            "path": str(out_path),
            "rel_path": f"icons/icon-{size}.png",
            "bytes": out_path.stat().st_size,
        })
    return results


def main() -> None:
    sizes = _read_manifest_sizes()
    print(f"Manifest icon sizes: {sizes}")
    ICONS_DIR.mkdir(parents=True, exist_ok=True)
    results = render_all(sizes)
    total = 0
    for r in results:
        total += r["bytes"]
        print(f"- {r['rel_path']}  {r['size']}x{r['size']}  {r['bytes']:,} bytes")
    print(f"Total: {len(results)} files, {total:,} bytes")


if __name__ == "__main__":
    sys.exit(main())